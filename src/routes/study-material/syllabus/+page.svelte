<li dir="ltr" role="presentation"><span>Prelims is only a screening test; its marks are not counted in the final merit list.</span></li>
<li dir="ltr" role="presentation"><span>Both papers are available in English and Hindi.</span></li>
<li dir="ltr" role="presentation"><span>The syllabus of GS Paper-I is brief but covers a wide range of subjects like History, Geography, Polity, Economy, Environment, Science, and Current Affairs.</span></li>
<li dir="ltr" role="presentation"><span>Current affairs are linked with almost every subject, so they should be studied in an integrated manner.</span></li>
