<li dir="ltr" role="presentation"><span>Functions and Responsibilities of the Union and the States, Issues and Challenges Pertaining to the Federal Structure, Devolution of Powers and Finances up to Local Levels and Challenges Therein.</span></li>
<li dir="ltr" role="presentation"><span>Separation of Powers between various organs Dispute Redressal Mechanisms and Institutions.</span></li>
