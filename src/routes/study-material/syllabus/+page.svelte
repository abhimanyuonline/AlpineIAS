<li dir="ltr" role="presentation"><span>Welfare Schemes for Vulnerable Sections of the population by the Centre and States and the Performance of these Schemes; Mechanisms, Laws, Institutions and Bodies constituted for the Protection and Betterment of these Vulnerable Sections.</span></li>
<li dir="ltr" role="presentation"><span>Issues Relating to Development and Management of Social Sector/Services relating to Health, Education, Human Resources.</span></li>
<li dir="ltr" role="presentation"><span>Issues relating to Poverty and Hunger.</span></li>
<li dir="ltr" role="presentation"><span>Important Aspects of Governance, Transparency and Accountability, E-governance- applications, models, successes, limitations, and potential; Citizens Charters, Transparency &amp; Accountability and institutional and other measures.</span></li>
<li dir="ltr" role="presentation"><span>Role of Civil Services in a Democracy.</span></li>
<li dir="ltr" role="presentation"><span>India and its Neighborhood- Relations.</span></li>
<li dir="ltr" role="presentation"><span>Bilateral, Regional and Global Groupings and Agreements involving India and/or affecting India’s interests.</span></li>
<li dir="ltr" role="presentation"><span>Effect of Policies and Politics of Developed and Developing Countries on India’s interests, Indian Diaspora.</span></li>
<li dir="ltr" role="presentation"><span>Important International Institutions, agencies and fora - their Structure, Mandate.</span><strong><b>&nbsp;</b></strong></li>
