<li dir="ltr" role="presentation"><span>Structure, Organization and Functioning of the Executive and the Judiciary—Ministries and Departments of the Government; Pressure Groups and Formal/Informal Associations and their Role in the Polity.</span></li>
<li dir="ltr" role="presentation"><span>Salient Features of the Representation of People’s Act.</span></li>
<li dir="ltr" role="presentation"><span>Appointment to various Constitutional Posts, Powers, Functions and Responsibilities of various Constitutional Bodies.</span></li>
