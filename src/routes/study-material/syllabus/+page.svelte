<h2><strong><b></b></strong><strong>UPSC Mains Syllabus: Paper-V/General Studies- IV</strong></h2>
</div>
<div dir="ltr" style="text-align: left;"><strong><b></b>Ethics, Integrity and Aptitude</strong></div>
<p dir="ltr"><span>This paper will include questions to test the candidates’ attitude and approach to issues relating to integrity, probity in public life and his problem solving approach to various issues and conflicts faced by him in dealing with society. Questions may utilise the case study approach to determine these aspects. The following broad areas will be covered:</span></p>
<ul style="list-style-type: square;">
<li dir="ltr" role="presentation"><span><strong>Ethics and Human Interface: </strong>Essence, Determinants and Consequences of Ethics in - Human Actions; Dimensions of Ethics; Ethics - in Private and Public Relationships. Human Values - Lessons from the Lives and Teachings of Great Leaders, Reformers and Administrators; Role of Family Society and Educational Institutions in Inculcating Values.</span></li>
<li dir="ltr" role="presentation"><span><strong>Attitude:</strong> Content, Structure, Function; its Influence and Relation with Thought and Behaviour; Moral and Political Attitudes; Social Influence and Persuasion.</span></li>
<li dir="ltr" role="presentation"><span>Aptitude and Foundational Values for Civil Service, Integrity, Impartiality and Non-partisanship, Objectivity, Dedication to Public Service, Empathy, Tolerance and Compassion towards the weaker-sections.</span></li>
<li dir="ltr" role="presentation"><span>Emotional Intelligence-Concepts, and their Utilities and Application in Administration and Governance.</span></li>
<li dir="ltr" role="presentation"><span>Contributions of Moral Thinkers and Philosophers from India and World.</span></li>
<li dir="ltr" role="presentation"><span>Public/Civil Service Values and Ethics in Public Administration: Status and Problems; Ethical Concerns and Dilemmas in Government and Private Institutions; Laws, Rules, Regulations and Conscience as Sources of Ethical Guidance; Accountability and Ethical Governance; Strengthening of Ethical and Moral Values in Governance; Ethical Issues in International Relations and Funding; Corporate Governance.</span></li>
<li dir="ltr" role="presentation"><span>Probity in Governance: Concept of Public Service; Philosophical Basis of Governance and Probity; Information Sharing and Transparency in Government, Right to Information, Codes of Ethics, Codes of Conduct, Citizen’s Charters, Work Culture, Quality of Service Delivery, Utilization of Public Funds, Challenges of Corruption.</span></li>
<li dir="ltr" role="presentation"><span>Case Studies on above issues.</span><strong><b></b></strong></li>
</ul>
