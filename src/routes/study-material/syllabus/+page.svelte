<h2 dir="ltr"><strong>UPSC Essay Syllabus (Paper-I)</strong></h2>
<p dir="ltr"><span>The UPSC Essay Paper evaluates clarity of thought, coherence, and depth. Candidates must write two essays, each from a choice of topics. Emphasis is on logical arrangement, effective expression, and relevance. Essays may touch on philosophical, social, economic, or political issues. Originality, critical thinking, and balanced viewpoints are highly rewarded in evaluation.</span><strong><b></b></strong></p>
<h2 dir="ltr"><strong>UPSC Mains Syllabus: Paper-II/General Studies-I<b></b></strong></h2>
<p dir="ltr"><span>&nbsp;Indian Heritage and Culture, History and Geography of the World and Society</span></p>
<ul style="list-style-type: square;">
<li dir="ltr" role="presentation"><span>Indian Culture - Salient aspects of Art Forms, Literature and Architecture from ancient to modern times.</span></li>
<li dir="ltr" role="presentation"><span>Modern Indian History from about the middle of the eighteenth century until the present- significant events, personalities, issues.</span></li>
<li dir="ltr" role="presentation"><span>The Freedom Struggle — its various stages and important contributors/contributions from different parts of the country.</span></li>
<li dir="ltr" role="presentation"><span>Post-independence Consolidation and Reorganization within the country.</span></li>
<li dir="ltr" role="presentation"><span>History of the World will include events from 18th century such as Industrial Revolution, world wars, Redrawal of National Boundaries, Colonization, Decolonization, political philosophies like Communism, Capitalism, Socialism etc.— their forms and effect on the society.</span></li>
<li dir="ltr" role="presentation"><span>Salient features of Indian Society, Diversity of India.</span></li>
<li dir="ltr" role="presentation"><span>Role of Women and Women’s Organization, Population and Associated Issues, Poverty and Developmental issues, Urbanization, their problems and their remedies.</span></li>
<li dir="ltr" role="presentation"><span>Effects of Globalization on Indian society.</span></li>
<li dir="ltr" role="presentation"><span>Social Empowerment, Communalism, Regionalism &amp; Secularism.</span></li>
<li dir="ltr" role="presentation"><span>Salient features of World’s Physical Geography.</span></li>
<li dir="ltr" role="presentation"><span>Distribution of Key Natural Resources across the world (including South Asia and the Indian sub-continent); factors responsible for the location of primary, secondary, and tertiary sector industries in various parts of the world (including India).</span></li>
<li dir="ltr" role="presentation"><span>Important Geophysical Phenomena such as earthquakes, Tsunami, Volcanic activity, cyclone etc., geographical features and their location-changes in critical geographical features (including water-bodies and ice-caps) and in flora and fauna and the effects of such changes.</span><strong><b></b></strong></li>
</ul>
